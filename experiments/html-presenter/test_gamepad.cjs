const assert = require('node:assert/strict');
const { GamepadControls } = require('./web/gamepad.js');

const actions = [];
const control = new GamepadControls(action => actions.push(action));
const pad = { index: 0, id: 'Synthetic standard controller', mapping: 'standard',
  buttons: Array.from({length: 17}, () => ({pressed: false})), axes: [0, 0] };
const sample = (now = 0) => control.update([null, pad], now);
sample();
pad.buttons[5].pressed = true;
sample(); sample(); sample();
assert.deepEqual(actions, ['next'], 'holding a bumper must advance only once');
pad.buttons[5].pressed = false; sample();
pad.buttons[5].pressed = true; sample();
assert.deepEqual(actions, ['next', 'next']);
pad.buttons[5].pressed = false; sample();
pad.buttons[3].pressed = true; sample(); sample();
assert.equal(actions.at(-1), 'answers');
pad.buttons[3].pressed = false; sample();
pad.axes[1] = 0.1; sample();
assert.equal(actions.at(-1), 'answers', 'stick drift must not trigger scrolling');
pad.axes[1] = 0.8; sample(100); sample(150); sample(260);
assert.deepEqual(actions.slice(-2), ['down', 'down']);
control.update([], 300);
const count = actions.length;
sample(400);
assert.equal(actions.length, count, 'reconnection must wait for release');
pad.axes[1] = 0; pad.buttons[5].pressed = false; sample(500);
pad.buttons[1].pressed = true; sample(600);
assert.equal(actions.at(-1), 'next');
control.update([pad], 700, false);
control.update([pad], 800, true);
assert.equal(actions.length, count + 1, 'returning to a visible tab must not replay held inputs');
pad.buttons[1].pressed = false; sample(850);
pad.buttons[2].pressed = true; sample(860);
assert.equal(actions.at(-1), 'previous', 'PS5 square goes back');
pad.buttons[2].pressed = false; sample(870);
pad.buttons[0].pressed = true; sample(880);
assert.equal(actions.at(-1), 'dismiss', 'PS5 cross dismisses answers');
pad.mapping = ''; pad.buttons[4].pressed = true; sample(900);
assert.equal(actions.length, count + 3, 'unknown mappings require calibration, never guessed actions');
console.log('PASS: controller edges, drift, scroll repeat, sparse slots, reconnect and visibility');
